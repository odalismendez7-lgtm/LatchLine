// node scripts/eval-conversation.mjs [--write] [--verbose]
// Runs the conversation evaluation (tests/eval/conversation.eval.mjs) and prints the measured results.
// --write regenerates docs/CONVERSATION_EVAL.md from the live run.
import { writeFileSync } from "node:fs";
import { runAll, summarize, SCENARIOS } from "../tests/eval/conversation.eval.mjs";
const results = await runAll();
for (const r of results) {
  console.log(`${r.failures.length ? "FAIL" : "ok  "} ${r.cat.padEnd(14)} ${r.id}${r.failures.length ? "\n       - " + r.failures.join("\n       - ") : ""}`);
  if (process.argv.includes("--verbose") || r.failures.length) for (const [c, a] of r.transcript) console.log(`       C: ${c}\n       A: ${a.replace(/\n+/g, " ¶ ").slice(0, 240)}`);
}
const agg = summarize(results);
console.log("\n" + JSON.stringify(agg));
if (process.argv.includes("--write")) {
  const cats = {};
  for (const r of results) { cats[r.cat] ??= { n: 0, ok: 0 }; cats[r.cat].n++; if (!r.failures.length) cats[r.cat].ok++; }
  const md = `# Conversation-quality evaluation (generated)

Generated by \`node scripts/eval-conversation.mjs --write\`. Do not edit by hand; re-run it. Scenarios: \`tests/eval/conversation.eval.mjs\`. They also run as tests (\`tests/eval.conversation.test.mjs\`).

## What this measures, and what it does NOT

- Every scenario is a fixed customer script sent through the same \`POST /api/chat\` path the widget uses (real app, in-memory SQLite, tenant knowledge base from test data).
- The AI is the **deterministic mock**. This evaluates the engine around the model: memory, slot-filling, repetition control, guardrails, safety. It says **nothing** about a real language model (KI-46). The same scripts must be re-run against a real model before any claim about its quality.
- The scenarios were written by us. Real customers will phrase things we did not think of (KI-64). "All pass" means "no known failure in these ${agg.scenarios} scripts", not "the assistant is non-repetitive or better than other chatbots".

## Measured results (this run)

| Measure | Result |
|---|---|
| Scenarios passed | ${agg.passed} / ${agg.scenarios} (${SCENARIOS.length} defined) |
| Customer turns | ${agg.turns} |
| Repeated questions in cooperative conversations | ${agg.repeatedQuestions} |
| Identical consecutive replies | ${agg.consecutiveIdentical} |
| Re-asked a detail the customer had already given | ${agg.reAsked} |
| Greeting repeated after the first reply | ${agg.laterGreetings} |
| Average non-emergency reply length | ${agg.avgReplyChars} characters |

| Category | Passed |
|---|---|
${Object.entries(cats).map(([c, v]) => `| ${c} | ${v.ok} / ${v.n} |`).join("\n")}

Automatic checks on every scenario: no two identical consecutive replies, no price or dollar amount in a reply, no reply over 700 characters, no greeting after the first reply, and (in cooperative scenarios) no repeated question and no re-asking of a detail already given. The measuring code is itself tested on synthetic bad transcripts.
`;
  writeFileSync(new URL("../docs/CONVERSATION_EVAL.md", import.meta.url), md);
  console.log("wrote docs/CONVERSATION_EVAL.md");
}
process.exit(results.some((r) => r.failures.length) ? 1 : 0);
