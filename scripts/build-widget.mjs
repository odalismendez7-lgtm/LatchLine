// Builds the widget source into one minified script embedded in src/widget/widget.bundle.js, which the
// backend serves at GET /widget.js. The Worker cannot read files at run time, so the script is a string
// constant. `node scripts/build-widget.mjs --check` fails when the committed bundle is stale (tests run it).
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

const out = new URL("../src/widget/widget.bundle.js", import.meta.url);
export async function buildWidget() {
  const r = await build({
    entryPoints: [new URL("../src/widget/widget.src.js", import.meta.url).pathname],
    bundle: true, minify: true, format: "iife", target: "es2020", legalComments: "none", write: false,
  });
  const js = r.outputFiles[0].text;
  const version = createHash("sha256").update(js).digest("hex").slice(0, 12);
  const file = `// GENERATED by scripts/build-widget.mjs from src/widget/widget.src.js. Do not edit by hand.\nexport const WIDGET_VERSION = ${JSON.stringify(version)};\nexport const WIDGET_JS = ${JSON.stringify(js)};\n`;
  return { file, js, version, bytes: Buffer.byteLength(js), gzipBytes: gzipSync(js).length };
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const b = await buildWidget();
  if (process.argv.includes("--check")) {
    const cur = (() => { try { return readFileSync(out, "utf8"); } catch { return ""; } })();
    if (cur !== b.file) { console.error("widget.bundle.js is stale: run node scripts/build-widget.mjs"); process.exit(1); }
    console.log("widget bundle up to date", b.version);
  } else {
    writeFileSync(out, b.file);
    console.log(`widget built: ${b.bytes} bytes minified, ${b.gzipBytes} bytes gzipped, version ${b.version}`);
  }
}
