// Notification text. Built ONLY from the lead and business records fetched
// through the tenant handle for this notification's business, so it cannot
// include another business's data. Customer-supplied text is flattened to one
// line (no header injection) and length-limited. Nothing here claims that
// anyone was contacted, dispatched, or that a visit is booked.

const CONTROL = new RegExp("[\\u0000-\\u001f\\u007f-\\u009f\\u2028\\u2029]+", "g");
const line = (v, max) => String(v ?? "").replace(CONTROL, " ").replace(/\s+/g, " ").trim().slice(0, max);

const CATEGORY_LABELS = { gas_leak: "gas smell", carbon_monoxide: "carbon monoxide", fire_smoke: "fire/smoke", electrical_hazard: "electrical hazard", water_heater_hazard: "water heater hazard", flooding: "flooding", sewage_backup: "sewage backup", life_threat: "possible injury", unspecified_emergency: "unspecified emergency" };

export function renderNotification({ kind, priority, channel, business, lead }) {
  const name = line(lead.name, 60) || "(no name)";
  const phone = line(lead.phone, 20) || "(no phone)";
  const zip = line(lead.zip, 5) || "(no ZIP)";
  const issue = line(lead.issue_text, 200) || "(no description)";
  const cats = (Array.isArray(lead.emergency_categories) ? lead.emergency_categories : []).map((c) => CATEGORY_LABELS[c] ?? "emergency").join(", ");
  const contactLine = `${name}, ${phone}, ZIP ${zip}`;
  const biz = line(business?.name, 80) || "your business";

  let head, body;
  if (priority === "emergency") {
    head = `EMERGENCY inquiry (${cats || "reported emergency"})`;
    body = `A customer reported a possible emergency. LATCHLINE cannot dispatch anyone and has not confirmed that anyone was helped. Contact the customer now: ${contactLine}. Issue: ${issue}`;
  } else if (kind === "human_requested") {
    head = priority === "urgent" ? "URGENT: customer asked for a person" : "Customer asked to speak with a person";
    body = `The customer asked for a person. Contact: ${contactLine}. Issue: ${issue}`;
  } else if (kind === "repeat_contact") {
    head = priority === "urgent" ? "URGENT: repeat inquiry" : "Repeat inquiry";
    body = `A customer who contacted you recently wrote again. Contact: ${contactLine}. Latest issue: ${issue}`;
  } else {
    head = priority === "urgent" ? "URGENT new inquiry" : "New inquiry";
    body = `New inquiry received. Contact: ${contactLine}. Issue: ${issue}`;
  }

  if (channel === "sms") return { text: `${head} - ${biz}: ${body}`.slice(0, 320) };
  return { subject: line(`${head} - ${biz}`, 150), text: `${body}\n\nThis message was generated by LATCHLINE from the customer's own words. It is not a confirmation of any visit or price.` };
}
